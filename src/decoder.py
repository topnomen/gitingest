#!/usr/bin/env python3

"""Decode JSON content embedded in model output."""

import json
from typing import Dict, Any


def extract_json(text: str) -> Dict[str, Any] | Any:
    """Extract and parse the first JSON object found in a string.

    Args:
        text: Raw text generated by the model.

    Returns:
        Parsed JSON object as a Python dictionary.

    Raises:
        ValueError: If no JSON object is found or the JSON is invalid.
    """
    text = text.strip()
    start = text.find('{')
    end = text.rfind('}')

    if start == -1 or end == -1:
        raise ValueError(f"No JSON found in: '{text}'")

    json_str = text[start:end + 1]
    json_str = json_str.replace('\n', ' ')
    json_str = json_str.replace('\t', ' ')
    json_str = json_str.replace('\r', ' ')

    try:
        return json.loads(json_str)
    except json.JSONDecodeError as error:
        raise ValueError(f"Invalid JSON: '{json_str}' -> {error}") from error
